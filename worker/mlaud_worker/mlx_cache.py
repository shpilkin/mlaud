"""Предел кэша Metal-буферов MLX для процессов распознавания.

MLX по умолчанию копит освобождённые буферы до лимита памяти устройства (45.6 ГБ на
48-гигабайтном Mac) и системе их не отдаёт. Окна разбора каждый раз разной длины, буферы
почти не переиспользуются: пакетный разбор 18-минутной записи копил ~29 ГБ, живой
распознаватель — 7 ГБ за 22 с звука. Модели нужно ~1.5 ГБ; предел 1 ГБ разбор не замедляет.
"""

CACHE_LIMIT_BYTES = 1 << 30


def limit_cache() -> None:
    """Поставить предел кэша MLX на весь процесс. Вызывать до загрузки модели."""
    import mlx.core as mx

    mx.set_cache_limit(CACHE_LIMIT_BYTES)
